
def area(a):
    '''
    Возвращает площадь квадрата.
        Параметр:
            a (float,int): сторона квадрата
        Возвращаемое значение:
            a**2 (float,int): значение площади квадрата со стороной a
    '''
    return a * a

def perimeter(a):
    '''
    Возвращает периметр квадрата.
        Параметр:
            a (float,int): сторона квадрата
        Возвращаемое значение:
            4*a (float,int): значение периметра квадрата со стороной a
    '''
    return 4 * a
